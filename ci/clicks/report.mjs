// The survey's tables, and how a run compares with an earlier one (the baseline).

const total = (j) => j.clicks + j.keys + j.prompts;

/** Per-journey changes from `base` to `now`: worse when a journey takes more, or fails where it passed. */
export function compare(now, base) {
  const before = new Map(base.journeys.map((j) => [j.id, j]));
  const out = [];
  for (const j of now.journeys) {
    const b = before.get(j.id);
    if (!b) {
      out.push({ id: j.id, what: "new", worse: false });
      continue;
    }
    if (!j.ok && b.ok) {
      out.push({ id: j.id, what: "fails now", worse: true });
      continue;
    }
    const d = { clicks: j.clicks - b.clicks, keys: j.keys - b.keys, prompts: j.prompts - b.prompts };
    if (d.clicks || d.keys || d.prompts)
      out.push({
        id: j.id,
        what: Object.entries(d)
          .filter(([, v]) => v)
          .map(([k, v]) => `${v > 0 ? "+" : ""}${v} ${k}`)
          .join(", "),
        delta: d,
        worse: total(j) > total(b),
      });
  }
  for (const b of base.journeys) if (!now.journeys.some((j) => j.id === b.id)) out.push({ id: b.id, what: "gone", worse: false });
  return out;
}

/** What each page asked of people across all journeys, with how far it is from Home and how busy it is. */
export function perPage(result) {
  const pages = new Map();
  const get = (key) => {
    if (!pages.has(key)) pages.set(key, { page: key, clicks: 0, keys: 0, prompts: 0, journeys: new Set() });
    return pages.get(key);
  };
  for (const j of result.journeys)
    for (const s of j.steps) {
      const p = get(s.page);
      p.clicks += s.clicks;
      p.keys += s.keys;
      p.prompts += s.prompts;
      p.journeys.add(j.id);
    }
  for (const s of result.pages || []) Object.assign(get(s.page), { label: s.label, reach: s.reach, controls: s.controls });
  return [...pages.values()]
    .map((p) => ({ ...p, journeys: [...p.journeys].sort() }))
    .sort((a, b) => a.page.localeCompare(b.page));
}

export function markdown(result, base) {
  const diff = base ? new Map(compare(result, base).map((d) => [d.id, d])) : null;
  const lines = [
    "# Clicks and keystrokes per feature",
    "",
    `Surveyed ${result.surveyed}${result.commit ? ` at ${result.commit.slice(0, 7)}` : ""}, Chromium ${result.viewport}.`,
    "Clicks include the click that focuses a field before typing; keys are characters typed plus keys and shortcuts",
    "pressed (a paste is one); prompts are passkey touches. Generated by ci/clicks; see its README for the rules.",
    "",
  ];
  const modules = [...new Set(result.journeys.map((j) => j.module))];
  let sum = { clicks: 0, keys: 0, prompts: 0 };
  lines.push(`| Module | Feature | Clicks | Keys | Prompts | Total | Pages${diff ? " | vs baseline" : ""} |`);
  lines.push(`|---|---|--:|--:|--:|--:|---${diff ? "|---" : ""}|`);
  for (const m of modules)
    for (const j of result.journeys.filter((x) => x.module === m)) {
      sum = { clicks: sum.clicks + j.clicks, keys: sum.keys + j.keys, prompts: sum.prompts + j.prompts };
      const pages = [...new Set(j.steps.map((s) => s.page))].join(", ");
      const d = diff?.get(j.id);
      const feature = j.ok ? j.feature : `${j.feature} (failed: ${j.error})`;
      lines.push(
        `| ${m} | ${feature} | ${j.clicks} | ${j.keys} | ${j.prompts} | ${total(j)} | ${pages}${diff ? ` | ${d ? d.what : "same"}` : ""} |`,
      );
    }
  lines.push(`| **All** | **${result.journeys.length} features** | **${sum.clicks}** | **${sum.keys}** | **${sum.prompts}** | **${sum.clicks + sum.keys + sum.prompts}** | |`);
  lines.push("", "## Per module", "", "| Module | Features | Clicks | Keys | Prompts |", "|---|--:|--:|--:|--:|");
  for (const m of modules) {
    const js = result.journeys.filter((x) => x.module === m);
    const s = (k) => js.reduce((n, j) => n + j[k], 0);
    lines.push(`| ${m} | ${js.length} | ${s("clicks")} | ${s("keys")} | ${s("prompts")} |`);
  }
  lines.push(
    "",
    "## Per page",
    "",
    "Reach is clicks from Home through the navigation; controls are the buttons, links and fields showing in the page's",
    "main area on a fresh install (a measure of how busy it is). Clicks and keys are what the features above did there.",
    "",
    "| Page | Reach | Controls | Clicks | Keys | Prompts | Features |",
    "|---|--:|--:|--:|--:|--:|---|",
  );
  for (const p of perPage(result))
    lines.push(
      `| ${p.label ? `${p.label} (\`${p.page}\`)` : `\`${p.page}\``} | ${p.reach ?? ""} | ${p.controls ?? ""} | ${p.clicks || ""} | ${p.keys || ""} | ${p.prompts || ""} | ${p.journeys.join(", ")} |`,
    );
  lines.push("", "## Steps", "");
  for (const j of result.journeys) {
    lines.push(`### ${j.module}: ${j.feature}`, "");
    if (j.note) lines.push(j.note, "");
    for (const s of j.steps) {
      const cost = [s.clicks && `${s.clicks} click${s.clicks > 1 ? "s" : ""}`, s.keys && `${s.keys} key${s.keys > 1 ? "s" : ""}`, s.prompts && "passkey"]
        .filter(Boolean)
        .join(" + ");
      lines.push(`1. \`${s.page}\` ${s.what} (${cost})`);
    }
    lines.push("");
  }
  return lines.join("\n");
}
